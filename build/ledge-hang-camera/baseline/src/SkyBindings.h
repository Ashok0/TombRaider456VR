#pragma once
#include <cstdint>

namespace tr::sky {
// PDB names plus instruction/call-target matching against both shipped builds.
// TR4/5: SkyDrawPhase, S_CmdFlush. TR6: DrawRoom_SYS_D3D_ROOM and pSkyRoom.
// Full prologues are checked before patching; the TR4 RIP load is relocated.
struct Binding {
    uint32_t timestamp,entry,flush,skyRoom;
    uint8_t prologue[11];
    uint8_t stolen;
    int rip;
};
constexpr Binding Bindings[] = {
    {0x696B4999,0x2F2E0,0xB1B50,0,{0x48,0x83,0xEC,0x38,0x48,0x8B,0x05,0x1D,0x4C,0x63,0x00},11,7},
    {0x68C12FDA,0x2F150,0xB26C0,0,{0x48,0x83,0xEC,0x38,0x48,0x8B,0x05,0xED,0x5C,0x63,0x00},11,7},
    {0x696B499C,0x30120,0xA5460,0,{0x48,0x83,0xEC,0x28,0x45,0x33,0xC0},7,-1},
    {0x68C12FE9,0x305A0,0xA5750,0,{0x48,0x83,0xEC,0x28,0x45,0x33,0xC0},7,-1},
    {0x696B49A4,0x1AF5E0,0,0x3AE940,{0x40,0x55,0x56,0x57,0x41,0x54},6,-1},
    {0x68C12FE6,0x1AFB00,0,0x3AD8A0,{0x40,0x55,0x56,0x57,0x41,0x54},6,-1},
};
inline const Binding* Find(uint32_t timestamp) {
    for(const auto& binding:Bindings) if(binding.timestamp==timestamp) return &binding;
    return nullptr;
}
} // namespace tr::sky
