from pathlib import Path
import json,struct,sys
import pefile
from capstone import *
from capstone.x86 import *
root=Path('C:/dev/TombRaider456VR');src=Path('C:/dev/TombRaider123VR')
steam=Path('C:/Program Files (x86)/Steam/steamapps/common/Tomb Raider IV-VI Remastered')
rows=[]
for g,f in [
 (1,[0x1fea0,0x34230,0x106908,0x11ee08,0x4f87e0,0x41dd94,0x41d6a0,0x119f90]),
 (2,[0x3b890,0x625b0,0x141da8,0x15e334,0x537940,0x4331e0,0x432790,0x159870]),
 (3,[0x4fe70,0x95ed0,0x192738,0x1b4950,0x596a40,0x491f74,0x4907d0,0x1afbb0])]:
 rows.append((g,src/f'PDB/tomb{g}.dll',f))
 for flavor in ['retail','egs']:
  d=json.loads((root/f'build/native-port{g}-{flavor}.json').read_text())
  rows.append((g,src/f'build/current-{flavor}-verify/tomb{g}.dll',d['fields']))
rows.extend([
 (4,root/'PDB/tomb4.dll',[0x37f70,0xed310,0x1bb1fc,0x1b7e38,0x1bb504,0x663f00,0x6600e0,0x1bb1b8]),
 (4,steam/'4/tomb4.dll',[0x37e80,0xedbf0,0x1bc13c,0x1b8e38,0x1bc444,0x664e40,0x661020,0x1bc0f8]),
 (5,root/'PDB/tomb5.dll',[0x38c30,0xe46d0,0x1b6c40,0x1b3ce8,0x1b6f74,0x65ac40,0x65abf0,0x1b6bf8]),
 (5,steam/'5/tomb5.dll',[0x39100,0xe4720,0x1b6b80,0x1b3ce8,0x1b6eb4,0x65ab80,0x65ab30,0x1b6b38]),
 (6,Path('C:/dev/PDB/tomb6.dll'),[0xc9e80,0,0x3de540,0x3e1a28,0x2fe018,0,0x43d5a0,0]),
 (6,steam/'6/tomb6.dll',[0xc9930,0,0x3dd4a0,0x3e0988,0x2fcf78,0,0x43c500,0])])
cs=Cs(CS_ARCH_X86,CS_MODE_64);cs.detail=True
header=['// Verified PDB/retail title-menu addresses. Generated by build/native_menu_addresses.py.','static constexpr Row Rows[]={']
report=[]
for g,path,f in rows:
 pe=pefile.PE(str(path));mem=pe.get_memory_mapped_image();stamp=pe.FILE_HEADER.TimeDateStamp
 def prefix(rva):
  if not rva:return b''
  n=0
  for ins in cs.disasm(mem[rva:rva+24],rva):
   assert not any(o.type==X86_OP_MEM and o.mem.base==X86_REG_RIP for o in ins.operands)
   assert not ins.group(CS_GRP_JUMP) and not ins.group(CS_GRP_CALL)
   n+=ins.size
   if n>=5: break
  assert 5<=n<=8
  return mem[rva:rva+n]
 a,b=prefix(f[0]),prefix(f[1])
 def arr(data):return '{'+','.join('0x%02x'%x for x in data)+'}'
 header.append('    {'+str(g)+','+','.join('0x%08x'%x for x in [stamp,*f])+f',{len(a)},{len(b)},'+arr(a)+','+arr(b)+'},')
 # Validate the critical globals against instructions in each title adapter.
 ranges=[(f[0],f[0]+(355 if g<=3 else 2200))]
 refs=set()
 for lo,hi in ranges:
  for i in cs.disasm(mem[lo:hi],lo):
   for o in i.operands:
    if o.type==X86_OP_MEM and o.mem.base==X86_REG_RIP:refs.add(i.address+i.size+o.mem.disp)
 if g<=3:
  assert f[2] in refs and f[4] in refs,(g,hex(stamp),'ring globals')
  for i in range(5):
   ptr=struct.unpack_from('<Q',mem,f[7]+8*i)[0]-pe.OPTIONAL_HEADER.ImageBase
   assert 0<ptr<len(mem)-3272
 elif g<=5:
  assert all(f[i] in refs for i in [2,3,4,5,6,7]),(g,hex(stamp),'title globals')
 else:assert f[3] in refs and f[4] in refs,(g,hex(stamp),'TR6 title dispatch')
 report.append({'game':g,'stamp':hex(stamp),'path':str(path),'fields':[hex(x) for x in f],'title_prologue':a.hex(),'draw_prologue':b.hex()})
header.append('};')
(root/'src/VRNativeMenuAddresses.inl').write_text('\n'.join(header)+'\n')
(root/'build/native-menu-address-audit.json').write_text(json.dumps(report,indent=2))
print(f'PASS: {len(rows)} native menu layouts, hook boundaries, and native data references verified')
