"""Offline flare release audit; reads PE bytes, never loads a game DLL."""
from pathlib import Path
import re, sys
from port_addresses import Image
from capstone.x86 import X86_OP_MEM, X86_OP_IMM, X86_REG_RIP

ROOT = Path(__file__).resolve().parents[1]
OLD = ROOT.parent / 'TombRaider123VR'
STEAM = Path(r'C:\Program Files (x86)\Steam\steamapps\common\Tomb Raider IV-VI Remastered')
BUILDS = [(OLD/'PDB/tomb2.dll',2,0x4E240), (OLD/'PDB/tomb3.dll',3,0x6CB60),
 (OLD/'build/current-retail-verify/tomb2.dll',2,0x4E2A0),
 (OLD/'build/current-retail-verify/tomb3.dll',3,0x6CEA0),
 (OLD/'build/current-october-verify/tomb2.dll',2,0x4DF40),
 (OLD/'build/current-october-verify/tomb3.dll',3,0x6D370),
 (ROOT/'PDB/tomb4.dll',4,0x60710), (ROOT/'PDB/tomb5.dll',5,0x5D680),
 (STEAM/'4/tomb4.dll',4,0x60430), (STEAM/'5/tomb5.dll',5,0x5E3C0)]

def fingerprint(data):
    h=14695981039346656037
    for b in data: h=((h^b)*1099511628211)&0xffffffffffffffff
    return h

def audit():
    rows=[]; profiles={}
    for path,game,undraw in BUILDS:
        im=Image(str(path)); end=undraw+{2:754,3:749,4:790,5:764}[game]
        ins=list(im.md.disasm(im.mem[undraw:end],im.base+undraw))
        # Verify the WHOLE routine, including the stage-33 cleanup beyond the
        # first unwind fragment, against that game's PDB build.
        normalized=[]
        for x in ins:
            operands=x.op_str
            operands=re.sub(r'\[rip [+-] 0x[0-9a-f]+\]', '[rip]', operands)
            if (x.mnemonic.startswith('j') or x.mnemonic=='call') and x.operands[0].type==X86_OP_IMM:
                operands='target'
            normalized.append((x.mnemonic,operands))
        if game in profiles: assert profiles[game]==normalized, f'TR{game} native release control flow changed'
        else: profiles[game]=normalized
        # Release event is arm frame 21; cleanup is frame 33. All supported
        # builds have the same normalized undraw control flow within each game.
        release=next(i for i,x in enumerate(ins) if x.mnemonic=='cmp' and x.op_str.endswith(', 0x15'))
        call=next(x for x in ins[release:release+10] if x.mnemonic=='call')
        create=call.operands[0].imm-im.base
        assert any(x.mnemonic=='cmp' and x.op_str.endswith(', 0x21') for x in ins)
        assert any(x.mnemonic=='mov' and x.op_str in ('ecx, 1','edx, 1') for x in ins[release:release+10])
        head=list(im.md.disasm(im.mem[create:create+64],im.base+create))
        exit_rva=next(x.operands[0].imm-im.base for x in head if x.mnemonic=='je')
        last=next(x for x in im.md.disasm(im.mem[exit_rva:exit_rva+32],im.base+exit_rva) if x.mnemonic=='ret')
        ce=last.address+last.size-im.base
        ci=list(im.md.disasm(im.mem[create:ce],im.base+create))
        assert ins[-1].mnemonic=='ret' and ins[-1].address+1==im.base+end
        free=next(x for x in ci if x.mnemonic=='movsx' and 'word ptr [rip' in x.op_str)
        nf=free.address+free.size+free.operands[1].mem.disp-im.base
        items=next((x for x in ci if x.mnemonic=='add' and 'qword ptr [rip' in x.op_str), None)
        if items is None: items=next(x for x in ci if x.mnemonic=='mov' and x.op_str.startswith('r8, qword ptr [rip'))
        items=items.address+items.size+items.operands[1].mem.disp-im.base
        assert any('0xfffffff0' in x.op_str for x in ci) # native wrist offset
        assert any(x.mnemonic=='mov' and x.op_str=='r8d, 0xd' for x in ci)
        assert any(' + 0x22]' in x.op_str for x in ci) # horizontal speed
        assert any(' + 0x24]' in x.op_str for x in ci) # vertical speed
        slot={2:152,3:179,4:372,5:354}[game]
        rows.append(f'    {{0x{im.stamp:X},{game},0x{undraw:X},{end-undraw},0x{fingerprint(im.mem[undraw:end]):016X}ull,'
                    f'0x{create:X},{ce-create},0x{fingerprint(im.mem[create:ce]):016X}ull,0x{nf:X},0x{items:X},{slot}}},')
        print(f'PASS TR{game} {im.stamp:08X}: release=21, cleanup=33, native allocation/position/speed verified')
    result='// Generated by tools/verify_flare_throw.py --write; audited native release routines.\n'+ '\n'.join(rows)+'\n'
    target=ROOT/'src/FlareThrowAddresses.inl'
    if '--write' in sys.argv: target.write_text(result)
    else: assert target.read_text()==result, 'Flare address fingerprints changed'

if __name__=='__main__': audit()
